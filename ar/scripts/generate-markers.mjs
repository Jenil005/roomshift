import QRCode from "qrcode";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Keep in sync with OBJECT_IDS (shared/constants) and TAG_PREFIX (ar/types.ts).
const OBJECTS = [
  { id: "book", label: "BOOK", theme: "KNOWLEDGE" },
  { id: "cup", label: "CUP", theme: "CONTAINMENT" },
  { id: "keyboard", label: "KEYBOARD", theme: "ACCESS" },
];
const payload = (id) => `roomshift:v1:${id}`;
const out = (path) => fileURLToPath(new URL(path, import.meta.url));

await mkdir(out("../public/markers/"), { recursive: true });
await mkdir(out("../print/"), { recursive: true });

const cards = [];
for (const { id, label, theme } of OBJECTS) {
  const svg = await QRCode.toString(payload(id), {
    type: "svg",
    errorCorrectionLevel: "M",
    margin: 4,
    width: 280,
  });
  await writeFile(out(`../public/markers/${id}.svg`), svg);
  cards.push(`    <article class="card">
      <h2>${label}</h2>
      <div class="qr">${svg.trim()}</div>
      <p>${theme} &middot; <code>${payload(id)}</code></p>
    </article>`);
}

const html = `<!doctype html>
<!-- Generated by ar/scripts/generate-markers.mjs. Do not edit by hand. -->
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>RoomShift Object Tags</title>
  <style>
    :root { color-scheme: light; }
    body { margin: 0; background: #fff; color: #111; font-family: system-ui, sans-serif; }
    header { padding: 16px; }
    header h1 { margin: 0 0 4px; font-size: 20px; }
    header p { margin: 0; font-size: 14px; color: #444; }
    .sheet { display: flex; flex-wrap: wrap; gap: 1cm; padding: 16px; }
    .card { width: 8.5cm; border: 1px dashed #999; padding: 0.6cm; box-sizing: border-box; text-align: center; break-inside: avoid; page-break-inside: avoid; }
    .card h2 { margin: 0 0 0.3cm; font-size: 32pt; letter-spacing: 0.1em; }
    /* 7 cm QR including its white quiet zone: keep it at least 6 cm when printed. */
    .qr svg { width: 7cm; height: 7cm; display: block; margin: 0 auto; background: #fff; }
    .card p { margin: 0.3cm 0 0; font-size: 9pt; color: #444; }
    @media print { header { display: none; } .sheet { padding: 0; } }
  </style>
</head>
<body>
  <header>
    <h1>RoomShift object tags</h1>
    <p>Print at 100% scale (no "fit to page"). Cut along the dashed line, keep the white border, and tape each tag to its object.</p>
  </header>
  <main class="sheet">
${cards.join("\n")}
  </main>
</body>
</html>
`;
await writeFile(out("../print/tags.html"), html);
console.log("Wrote ar/public/markers/*.svg and ar/print/tags.html");
